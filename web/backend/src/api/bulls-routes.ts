/**
 * WEB_BULLS_CONFIG routes - the Bulls door menu, editable from the admin.
 *
 * Sysop-only like every other board-file writer. GET answers the parsed
 * config with its problems; PUT saves exact bytes (the service keeps one
 * .bak) and answers the rechecked parse.
 */
import express, { Request, Response } from 'express';
import { getSystemTime } from '../utils/date-time.util';
import { loadBullsConfig, saveBullsConfig, saveBullsMenuEntries, listBulletins, readBulletin, writeBulletin } from '../services/bulls-config.service';

export function createBullsRouter(bbsRoot: string): ReturnType<typeof express.Router> {
  const router = express.Router();

  router.get('/', (_req: Request, res: Response) => {
    try {
      const { raw, parsed } = loadBullsConfig(bbsRoot);
      res.json({ success: true, data: { raw, ...parsed }, timestamp: getSystemTime().toISOString() });
    } catch (error) {
      res.status(500).json({
        success: false,
        message: error instanceof Error ? error.message : 'Failed to load Bulls.CFG',
      });
    }
  });

  router.put('/', (req: Request, res: Response) => {
    const { raw } = req.body ?? {};
    if (typeof raw !== 'string' || !raw) {
      res.status(400).json({ success: false, message: 'raw file text is required' });
      return;
    }
    try {
      const parsed = saveBullsConfig(bbsRoot, raw);
      res.json({ success: true, data: { raw, ...parsed }, timestamp: getSystemTime().toISOString() });
    } catch (error) {
      res.status(500).json({
        success: false,
        message: error instanceof Error ? error.message : 'Failed to save Bulls.CFG',
      });
    }
  });

  // Structured menu edit: one row per bull number. Only the menu section
  // is rewritten; settings, masks and title art pass through byte-identical.
  router.put('/entries', (req: Request, res: Response) => {
    const { entries } = req.body ?? {};
    if (!Array.isArray(entries)) {
      res.status(400).json({ success: false, message: 'entries must be an array of {title, file}' });
      return;
    }
    try {
      const parsed = saveBullsMenuEntries(bbsRoot, entries);
      const raw = loadBullsConfig(bbsRoot).raw;
      res.json({ success: true, data: { raw, ...parsed }, timestamp: getSystemTime().toISOString() });
    } catch (error) {
      const structural = error instanceof Error && /needs a title|bare filename|no menu section/.test(error.message);
      res.status(structural ? 400 : 500).json({
        success: false,
        message: error instanceof Error ? error.message : 'Failed to save bull entries',
      });
    }
  });

  // Bulletin content: every bull*.txt lists; generated ones (batches own
  // 1-6, the news service owns 7-8) read but never write through here.
  router.get('/bulletins', (_req: Request, res: Response) => {
    try {
      res.json({ success: true, data: { bulletins: listBulletins(bbsRoot) }, timestamp: getSystemTime().toISOString() });
    } catch (error) {
      res.status(500).json({
        success: false,
        message: error instanceof Error ? error.message : 'Failed to list bulletins',
      });
    }
  });

  router.get('/bulletins/:name', (req: Request, res: Response) => {
    try {
      const content = readBulletin(bbsRoot, req.params.name);
      res.json({ success: true, data: { name: req.params.name, content }, timestamp: getSystemTime().toISOString() });
    } catch (error) {
      const badName = error instanceof Error && error.message.startsWith('Not a bulletin file');
      res.status(badName ? 400 : 404).json({
        success: false,
        message: error instanceof Error ? error.message : 'Failed to read bulletin',
      });
    }
  });

  router.put('/bulletins/:name', (req: Request, res: Response) => {
    const { content } = req.body ?? {};
    if (typeof content !== 'string') {
      res.status(400).json({ success: false, message: 'content text is required' });
      return;
    }
    try {
      const info = writeBulletin(bbsRoot, req.params.name, content);
      res.json({ success: true, data: info, timestamp: getSystemTime().toISOString() });
    } catch (error) {
      const msg = error instanceof Error ? error.message : 'Failed to save bulletin';
      const generated = /is generated by/.test(msg);
      const badName = /Not a bulletin file/.test(msg);
      res.status(generated ? 403 : badName ? 400 : 500).json({ success: false, message: msg });
    }
  });

  return router;
}
