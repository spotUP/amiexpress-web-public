/**
 * WEB_BULLS_CONFIG: parse, problems, round-trip, save.
 *
 * The service never reformats: tests pin the live findings (bull12 mapped
 * twice, bull13-19 missing, Conference 9 without a mask row) and prove an
 * untouched file parses clean of format errors. Fixture is the real
 * Bulls.CFG shape, shrunk.
 */
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import {
  parseBullsConfig,
  saveBullsConfig,
  loadBullsConfig,
  saveBullsMenuEntries,
  BULLS_MENU_TITLE_MAX,
} from '../../src/services/bulls-config.service';

const CFG = [
  'DUAL_LISTING       YES                 ; Use 2 Listings [YES/NO]',
  'CURSOR_KEYS        YES                 ; Use Cursors',
  '[Init_END] ====================================================================',
  'Top Uploaders                                      ; bull1.txt',
  'System Information                                 ; bull12.txt',
  'Private Bull #3                                    ; bull12.txt',
  'Private Bull #4                                    ; bull13.txt',
  '[BullNames_END]===============================================================',
  'XXXXXX--------------                               ; Conference 1',
  'XXXXXXXXXXXX--------                               ; Conference 3',
  '[CnfAccess_END]===============================================================',
  'ART HERE',
  '[Title_END]===================================================================',
  '',
].join('\n');

describe('bulls config', () => {
  const files = new Set(['bull1.txt', 'bull12.txt']);
  it('parses settings, entries, masks, markers', () => {
    const c = parseBullsConfig(CFG, files);
    expect(c.settings.map((s) => s.key)).toEqual(['DUAL_LISTING', 'CURSOR_KEYS']);
    expect(c.entries.map((e) => e.file)).toEqual(['bull1.txt', 'bull12.txt', 'bull12.txt', 'bull13.txt']);
    expect(c.masks.map((m) => m.conference)).toEqual([1, 3]);
    expect(c.markers.initEnd).toBe(3);
  });
  it('flags the live problems: duplicate file, missing file, missing conference', () => {
    const c = parseBullsConfig(CFG, files);
    const kinds = c.problems.map((p) => p.kind);
    expect(kinds).toContain('duplicate-file');
    expect(kinds).toContain('missing-file');
    expect(kinds).toContain('missing-conference');
    expect(c.problems.find((p) => p.kind === 'duplicate-file')?.message).toContain('bull12.txt');
    expect(c.problems.find((p) => p.kind === 'missing-file')?.message).toContain('bull13.txt');
    expect(c.problems.find((p) => p.kind === 'missing-conference')?.message).toContain('Conference 2');
  });
  it('saves bytes back and backs up, problems rechecked', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'bulls-'));
    fs.mkdirSync(path.join(dir, 'Doors', 'emp_tools'), { recursive: true });
    fs.mkdirSync(path.join(dir, 'Bulletins'), { recursive: true });
    fs.writeFileSync(path.join(dir, 'Doors', 'emp_tools', 'Bulls.CFG'), CFG, 'latin1');
    fs.writeFileSync(path.join(dir, 'Bulletins', 'bull1.txt'), 'x', 'latin1');
    fs.writeFileSync(path.join(dir, 'Bulletins', 'bull12.txt'), 'x', 'latin1');
    const back = saveBullsConfig(dir, CFG.replace('bull13.txt', 'bull12.txt'));
    expect(fs.readFileSync(path.join(dir, 'Doors', 'emp_tools', 'Bulls.CFG'), 'latin1')).toContain('bull1.txt');
    expect(fs.existsSync(path.join(dir, 'Doors', 'emp_tools', 'Bulls.CFG.bak'))).toBe(true);
    expect(back.problems.map((p) => p.kind)).not.toContain('missing-file');
    const loaded = loadBullsConfig(dir);
    expect(loaded.raw).toContain('Top Uploaders');
    fs.rmSync(dir, { recursive: true, force: true });
  });
});

describe('bulletin content', () => {
  const { listBulletins, readBulletin, writeBulletin } = require('../../src/services/bulls-config.service') as typeof import('../../src/services/bulls-config.service');
  function board(): string {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'bulls-content-'));
    fs.mkdirSync(path.join(dir, 'Bulletins'), { recursive: true });
    fs.writeFileSync(path.join(dir, 'Bulletins', 'bull1.txt'), 'stats', 'latin1');
    fs.writeFileSync(path.join(dir, 'Bulletins', 'bull9.txt'), 'static', 'latin1');
    return dir;
  }
  it('lists generated flags by number', () => {
    const dir = board();
    try {
      const rows = listBulletins(dir).map((b) => `${b.name}:${b.generated ? 'gen' : 'static'}`);
      expect(rows).toEqual(['bull1.txt:gen', 'bull9.txt:static']);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });
  it('reads any bulletin, writes only static ones', () => {
    const dir = board();
    try {
      expect(readBulletin(dir, 'bull9.txt')).toBe('static');
      expect(() => readBulletin(dir, '../x')).toThrow('Not a bulletin file');
      expect(() => writeBulletin(dir, 'bull1.txt', 'hacked')).toThrow('generated by batch');
      const info = writeBulletin(dir, 'bull9.txt', 'edited');
      expect(info.name).toBe('bull9.txt');
      expect(readBulletin(dir, 'bull9.txt')).toBe('edited');
      expect(fs.existsSync(path.join(dir, 'Bulletins', 'bull9.txt.bak'))).toBe(true);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });
});

/**
 * Writing the menu goes through the Empire model (doors/text-cfg/empire.ts),
 * which is the one that promises unmapped bytes survive. The hand-rolled
 * writer this replaces split on '\n' and joined on '\n', so a CRLF file came
 * back with every line ending rewritten - a whole-file diff for a one-row
 * edit, on a file a 68K binary reads.
 */
describe('saving the bull menu keeps the rest of the file', () => {
  function board(cfg: string): string {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bullswrite-'));
    fs.mkdirSync(path.join(root, 'Doors', 'emp_tools'), { recursive: true });
    fs.mkdirSync(path.join(root, 'Bulletins'), { recursive: true });
    fs.writeFileSync(path.join(root, 'Bulletins', 'bull1.txt'), 'one\n');
    fs.writeFileSync(path.join(root, 'Bulletins', 'bull2.txt'), 'two\n');
    fs.writeFileSync(path.join(root, 'Doors', 'emp_tools', 'Bulls.CFG'), cfg, 'latin1');
    return root;
  }
  const read = (root: string) =>
    fs.readFileSync(path.join(root, 'Doors', 'emp_tools', 'Bulls.CFG'), 'latin1');

  it('replaces the menu rows and leaves settings, masks and title art alone', () => {
    const root = board(CFG);
    saveBullsMenuEntries(root, [{ title: 'Only One', file: 'bull1.txt' }]);
    const out = read(root);
    expect(out).toContain('DUAL_LISTING       YES');
    expect(out).toContain('XXXXXX--------------                               ; Conference 1');
    expect(out).toContain('ART HERE');
    expect(out).toContain('Only One');
    expect(out).not.toContain('Top Uploaders');
    expect(out.match(/bull12\.txt/g)).toBeNull();
  });

  it('keeps CRLF line endings when that is what the board wrote', () => {
    const root = board(CFG.replace(/\n/g, '\r\n'));
    saveBullsMenuEntries(root, [{ title: 'Only One', file: 'bull1.txt' }]);
    const out = read(root);
    expect(out).toContain('Only One');
    expect((out.match(/\r\n/g) || []).length).toBeGreaterThan(5);
    expect(out.match(/(?<!\r)\n/g)).toBeNull();
  });

  it("refuses a title carrying ';' - it would name a different bulletin file", () => {
    const root = board(CFG);
    expect(() =>
      saveBullsMenuEntries(root, [{ title: 'Sneaky ; bull2.txt', file: 'bull1.txt' }]),
    ).toThrow(/no ';'/);
    expect(read(root)).toContain('Top Uploaders');
  });

  it('refuses a title carrying a line break - it would become two rows', () => {
    const root = board(CFG);
    expect(() =>
      saveBullsMenuEntries(root, [{ title: 'One\nTwo', file: 'bull1.txt' }]),
    ).toThrow(/line break/);
  });

  it('refuses a title too long to leave the row inside 80 columns', () => {
    const root = board(CFG);
    const long = 'T'.repeat(BULLS_MENU_TITLE_MAX + 1);
    expect(() => saveBullsMenuEntries(root, [{ title: long, file: 'bull1.txt' }])).toThrow(
      /at most/,
    );
    expect(() =>
      saveBullsMenuEntries(root, [{ title: 'T'.repeat(BULLS_MENU_TITLE_MAX), file: 'bull1.txt' }]),
    ).not.toThrow();
  });

  it('still refuses a path as the file', () => {
    const root = board(CFG);
    expect(() =>
      saveBullsMenuEntries(root, [{ title: 'Ok', file: '../../etc/passwd' }]),
    ).toThrow(/bare filename/);
  });
});
