/**
 * A theme cannot carry a file the board writes for itself.
 *
 * `Bulletins/bull9.txt` is rewritten by the REQUESTS door whenever a caller
 * adds or changes a request. The theme studio's "redraw this" copied it into
 * `Themes/h7/Files/Bulletins/bull9.txt` on 2026-09-12, and the loader offers a
 * theme's `Files/` mirror FIRST - so every h7 caller read the requests list as
 * it stood that day, for a month, while the door kept writing the board's copy.
 *
 * Both halves: the copy refuses it, and a copy already in a theme does not
 * shadow it. MultiTop's bull1-5 are caught by content, bull9 by name, and a
 * hand-drawn bulletin beside them is still the theme's to redraw.
 */
process.env.SKIP_DB_INIT = '1';

const users: Array<{ username: string }> = [{ username: 'sysop' }];
jest.mock('../../src/services/UserFileManager', () => ({
  userFileManager: { readAllUsers: () => users },
}));

import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

import { config } from '../../src/config';
import { clearThemeRegistryCache, readThemeRegistry, writeTheme } from '../../src/screens/theme-registry';
import { invalidateScreenIndex } from '../../src/screens/screen-index.service';
import { copyScreenIntoTheme } from '../../src/screens/theme-seeding';
import { themedPath } from '../../src/screens/screen-resolution';

let root: string;
let previousDataDir: string;

const write = (rel: string, body: string) => {
  const full = path.join(root, rel);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, body, 'latin1');
};
const themeFile = (rel: string) => path.join(root, 'Themes', 'h7', rel);

beforeEach(() => {
  root = fs.mkdtempSync(path.join(os.tmpdir(), 'theme-generated-'));
  previousDataDir = config.get('dataDir');
  config.set('dataDir', root);
  fs.writeFileSync(path.join(root, 'ConfConfig.info'), '');

  write('Bulletins/bull9.txt', 'the requests list, as the door wrote it today\r\n');
  write('Bulletins/bull1.txt', 'Top Uploaders - generated by MultiTop-II\r\n');
  write('Bulletins/bull10.txt', 'hand-drawn art\r\n');

  fs.mkdirSync(themeFile(''), { recursive: true });
  clearThemeRegistryCache();
  writeTheme(root, {
    slug: 'h7', title: 'H7', author: 'skope', owner: 'skope',
    dir: path.join('Themes', 'h7'), widths: [80], doorTheme: '', status: 'live',
  });
  clearThemeRegistryCache();
  invalidateScreenIndex();
});

afterEach(() => {
  config.set('dataDir', previousDataDir);
  fs.rmSync(root, { recursive: true, force: true });
  clearThemeRegistryCache();
  invalidateScreenIndex();
});

const theme = () => readThemeRegistry(root).themes.find(entry => entry.slug === 'h7')!;

describe('a board-written bulletin and a theme', () => {
  it('redraw refuses to copy the REQUESTS door bulletin into the theme', () => {
    const result = copyScreenIntoTheme(root, theme(), 'Bulletins/bull9.txt');
    expect(result.copied).toEqual([]);
    expect(fs.existsSync(themeFile('Files/Bulletins/bull9.txt'))).toBe(false);
  });

  it('redraw still copies a hand-drawn bulletin', () => {
    const result = copyScreenIntoTheme(root, theme(), 'Bulletins/bull10.txt');
    expect(result.copied.map(entry => entry.target)).toEqual([path.join('Files', 'Bulletins', 'bull10.txt')]);
  });

  it('a stale theme copy of bull9 or a MultiTop bulletin does not shadow the board file', () => {
    write('Themes/h7/Files/Bulletins/bull9.txt', 'the requests list frozen on 2026-09-12\r\n');
    write('Themes/h7/Files/Bulletins/bull1.txt', 'Top Uploaders - frozen\r\n');
    expect(themedPath(root, 'h7', path.join(root, 'Bulletins/bull9.txt'))).toBeNull();
    expect(themedPath(root, 'h7', path.join(root, 'Bulletins/bull1.txt'))).toBeNull();
  });

  it('a theme copy of a hand-drawn bulletin still wins', () => {
    write('Themes/h7/Files/Bulletins/bull10.txt', 'the artist\'s redraw\r\n');
    expect(themedPath(root, 'h7', path.join(root, 'Bulletins/bull10.txt')))
      .toBe(themeFile('Files/Bulletins/bull10.txt'));
  });
});
