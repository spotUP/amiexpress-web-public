#!/usr/bin/env python3
"""
Lift GLCViewer's art and row templates out of the E source it was drawn in.

`GLCViewer.e` is in this repo, its string literals hold REAL escape bytes, and
it is the only description of what the 68K door puts on the wire. Transcribing
it by hand is how the abandoned port came to write spaces where the original
writes `ESC[5C` - the same picture on a blank line and different bytes.

So nothing is transcribed. This reads the source, and the test beside the
generated file reads it again and compares, so a logo edited in one place and
not the other fails rather than drifts.

Usage:  python3 dev/extract-art.py > src/art.generated.ts
"""
import io, json, re, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
E = os.path.join(
    os.environ.get('AMIEXPRESS_REFERENCE', '~/Code/Reference'),
    'AmiExpressEDoorSources/Global Last Callers/GLCViewer.e',
)

LITERAL = re.compile(r"(?:transmit|StrAdd)\((?:tempStr,)?'(.*)'\)\s*$")
STRINGF = re.compile(r"StringF\(writeStr,'(.*?)',(.+)\)\s*$")


def lines_of(path):
    return io.open(path, encoding='latin-1', newline='').read().split('\n')


def literals_between(lines, start_pred, end_pred, skip=lambda s: False):
    """Every transmit()/StrAdd() literal between two markers."""
    out, inside = [], False
    for raw in lines:
        s = raw.strip()
        if not inside:
            if start_pred(s):
                inside = True
            continue
        if end_pred(s):
            break
        if skip(s):
            continue
        m = LITERAL.search(s)
        if m:
            out.append(m.group(1))
    return out


def stringf_after(lines, pred, count):
    """The next `count` StringF templates after a marker line."""
    out, inside = [], False
    for raw in lines:
        s = raw.strip()
        if not inside:
            if pred(s):
                inside = True
            continue
        m = STRINGF.search(s)
        if m:
            out.append(m.group(1))
            if len(out) == count:
                break
    return out


def unescape_e(s):
    r"""E doubles a backslash inside a literal; everything else is a real byte."""
    return s.replace('\\\\', '\\')


def emit(name, value, comment):
    print(f'/** {comment} */')
    if isinstance(value, list):
        print(f'export const {name}: readonly string[] = [')
        for v in value:
            print(f'  {json.dumps(unescape_e(v))},')
        print('];\n')
    else:
        print(f'export const {name} = {json.dumps(unescape_e(value))};\n')


def main():
    lines = lines_of(E)

    is13 = lambda s: s.startswith('IF (style=1) OR (style=3)')
    is24 = lambda s: s.startswith('IF (style=2) OR (style=4)')
    endif = lambda s: s == 'ENDIF'
    # The column-header pair sits inside an IF showlocation; take the art only.
    art_only = lambda s: s.startswith('IF showlocation') or s.startswith('ELSE')

    head13 = literals_between(lines, is13, endif)
    head24 = literals_between(lines, is24, endif)

    print('/* GENERATED by dev/extract-art.py from GLCViewer.e - do not edit by hand.')
    print(' * Re-run after any change to the E source; the parity test compares them.')
    print(' */\n')

    # The last three literals of each header block are the banner and the two
    # column-header variants; the rest is the logo.
    emit('LOGO_STYLE_1_3', head13[:-3], 'Styles 1 and 3: the SdN logo, six lines.')
    emit('BANNER_1_3', head13[-3], 'The reverse-video title bar under the logo.')
    emit('COLUMNS_LOCATION_1_3', head13[-2], 'Column header when a location is shown.')
    emit('COLUMNS_BBS_1_3', head13[-1], 'Column header when the BBS name is shown instead.')

    emit('LOGO_STYLE_2_4', head24[:-3], 'Styles 2 and 4: the dotted logo, six lines.')
    emit('BANNER_2_4', head24[-3], 'The title bar for the second pair.')
    emit('COLUMNS_LOCATION_2_4', head24[-2], 'Column header when a location is shown.')
    emit('COLUMNS_BBS_2_4', head24[-1], 'Column header when the BBS name is shown instead.')

    rulers = [s for s in (LITERAL.search(l.strip()) for l in lines) if s]
    ruler_v = next(m.group(1) for m in rulers if 'v---' in m.group(1))
    ruler_c = next(m.group(1) for m in rulers if '^---' in m.group(1))
    plain = [m.group(1) for m in rulers if re.match(r'^\x1b\[34m-+(\x1b\[0m)?$', m.group(1))]
    emit('RULER_TOP', ruler_v, 'The column rule above the calls, with its column marks.')
    emit('RULER_BOTTOM', ruler_c, 'The same rule under the calls, marks inverted.')
    emit('RULE_PLAIN', plain[0], 'A plain rule - drawn under the legend.')
    emit('RULE_FINAL', plain[-1], 'The last rule of all, which also resets the pen.')

    legend = literals_between(
        lines,
        lambda s: s.startswith("transmit('\x1b[34m------------------^"),
        lambda s: re.match(r"^transmit\('\x1b\[34m-+'\)$", s) is not None,
    )
    emit('LEGEND', legend, "The action-letter key: [D]OWNLOAD, [u]PLOAD FAIL and the rest.")

    row = stringf_after(lines, lambda s: s.startswith('IF callsdata=9'), 1)
    emit('ROW_TEMPLATE', row[0], 'One call. E StringF codes; see estringf.ts.')

    foot12 = stringf_after(lines, lambda s: s.startswith('IF (style=1) OR (style=2)'), 3)
    foot34 = stringf_after(lines, lambda s: s.startswith('IF (style=3) OR (style=4)'), 3)
    emit('FOOTER_1_2', foot12, 'Styles 1 and 2: two day rows and the all-time record.')
    emit('FOOTER_3_4', foot34, 'Styles 3 and 4: the same days beside the top-three table.')


main()
